.MODEL SMALL
.STACK 100H
 
.DATA
   
   NUM1 DW 30000
   NUM2 DW 20000
   NUM3 DW 10000
   RESULT DW ?
   MSG DB 'SUBTRACTION = $'
   
   
.CODE

MAIN PROC
   
   MOV AX, @DATA
   MOV DS, AX
   
   ;ADD THREE NUMBERS
   MOV AX, NUM1
   SUB AX, NUM2
   SUB AX, NUM3
   
   ;STORE TO THE RESULT
   MOV RESULT, AX
   
   ;DISPLAY MESSAGE
   MOV AH, 09H
   LEA DX, MSG
   INT 21H
   
   ;CONVERT NUMBER INTO DECIMAL DIGITS
   MOV AX, RESULT
   MOV BX, 10
   MOV CX, 0
   
   CONVERT:
   
   MOV DX, 0 ;ISOLATED DIGITS
   DIV BX    ;DIVIDE BX WITH AX TO ISOLATE DIGITS
   PUSH DX   ;PUSH ISOLATED DIGIT TO STACK, SO IT CAN BE ACCESSED IN REVERSE ORDER
   INC CX    ;INCREASE CX SO NUMBER OF LOOPS ITERATION CAN BE DETERMINED
   CMP AX, 0 ;COMPARE AX, IF AX IS NOT 0 THAN GOT TO CONVERT ELSE DONT
   JNE CONVERT
   
   DISPLAY:
   
   POP DX        ;POP THE ISOLATED DIGITS
   ADD DL, 30H   ;ASCII SHIFT
   MOV AH, 02H   ;CHARACTER OUTPUT COMMAND
   INT 21H
   LOOP DISPLAY
   
   
   MOV AH, 4CH
   INT 21H  
    
MAIN ENDP
END MAIN

